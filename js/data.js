// Urutkan Santri Berdasarkan Abjad Nama (A - Z)
function sortSantriData(list) {
    if (!Array.isArray(list)) return [];
    return list.sort((a, b) => (a.nama || '').localeCompare(b.nama || '', 'id', { sensitivity: 'base' }));
}

